CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE
        CHECK (email <> '' AND email = lower(btrim(email))),
    password_hash VARCHAR(255) NOT NULL CHECK (btrim(password_hash) <> ''),
    display_name VARCHAR(200) NOT NULL CHECK (btrim(display_name) <> ''),
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'INSTRUCTOR')),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE workshops (
    workshop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    description VARCHAR(5000) NOT NULL CHECK (btrim(description) <> ''),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    location VARCHAR(300) NOT NULL CHECK (btrim(location) <> ''),
    max_participants INTEGER NOT NULL CHECK (max_participants > 0),
    instructor_id BIGINT NOT NULL,
    CONSTRAINT fk_workshops_instructor
        FOREIGN KEY (instructor_id)
        REFERENCES accounts (account_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_workshops_positive_duration
        CHECK (ends_at > starts_at)
);

CREATE INDEX ix_workshops_instructor_id
    ON workshops (instructor_id);

CREATE INDEX ix_workshops_starts_at
    ON workshops (starts_at);

CREATE TABLE registrations (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workshop_id BIGINT NOT NULL,
    participant_name VARCHAR(200) NOT NULL
        CHECK (btrim(participant_name) <> ''),
    email_normalized VARCHAR(320) NOT NULL,
    phone_number VARCHAR(40)
        CHECK (phone_number IS NULL OR btrim(phone_number) <> ''),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_registrations_email_normalized
        CHECK (email_normalized <> '' AND email_normalized = lower(btrim(email_normalized))),
    CONSTRAINT uq_registrations_workshop_email
        UNIQUE (workshop_id, email_normalized),
    CONSTRAINT fk_registrations_workshop
        FOREIGN KEY (workshop_id)
        REFERENCES workshops (workshop_id)
        ON DELETE RESTRICT
);

CREATE INDEX ix_registrations_workshop_registered_at
    ON registrations (workshop_id, registered_at);

CREATE TABLE email_outbox (
    email_outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL UNIQUE,
    recipient_email VARCHAR(320) NOT NULL
        CHECK (recipient_email <> '' AND recipient_email = lower(btrim(recipient_email))),
    subject VARCHAR(200) NOT NULL CHECK (btrim(subject) <> ''),
    message_body VARCHAR(10000) NOT NULL CHECK (btrim(message_body) <> ''),
    delivery_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (delivery_status IN ('PENDING', 'SENT', 'FAILED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    last_error VARCHAR(2000),
    CONSTRAINT ck_email_outbox_sent_at
        CHECK (
            (delivery_status = 'SENT' AND sent_at IS NOT NULL)
            OR (delivery_status IN ('PENDING', 'FAILED') AND sent_at IS NULL)
        ),
    CONSTRAINT fk_email_outbox_registration
        FOREIGN KEY (registration_id)
        REFERENCES registrations (registration_id)
        ON DELETE RESTRICT
);

CREATE INDEX ix_email_outbox_pending_next_attempt_at
    ON email_outbox (next_attempt_at)
    WHERE delivery_status = 'PENDING';
